import sqlite3
import random

# Connexion à la base de données
conn = sqlite3.connect('CleanWay.db')
cur = conn.cursor()

# Supprimer les tables si elles existent
cur.execute("DROP TABLE IF EXISTS Transactions")
cur.execute("DROP TABLE IF EXISTS Rendezvous")
cur.execute("DROP TABLE IF EXISTS Photos")
cur.execute("DROP TABLE IF EXISTS Factures")
cur.execute("DROP TABLE IF EXISTS Clients")
cur.execute("DROP TABLE IF EXISTS Entreprises")
cur.execute("DROP TABLE IF EXISTS Marque")
cur.execute("DROP TABLE IF EXISTS Modele")

# Activer les clés étrangères
conn.execute('PRAGMA foreign_keys = ON')

# Création des tables 

# Table Entreprises
cur.execute("""CREATE TABLE IF NOT EXISTS Entreprises (
            id INTEGER PRIMARY KEY AUTOINCREMENT UNIQUE,
            denomination TEXT NOT NULL,
            num_rue TEXT NOT NULL CHECK (num_rue GLOB '[0-9]* *[a-zA-Z]*'),
            code_postale TEXT NOT NULL CHECK (LENGTH(code_postale) == 5 AND code_postale GLOB '[0-9]*'),
            ville TEXT NOT NULL,
            telephone TEXT NOT NULL,
            email TEXT NOT NULL CHECK (email LIKE '%_@__%.__%'),
            siret TEXT NOT NULL CHECK (LENGTH(siret) = 14 AND siret GLOB '[0-9]*'),
            siren TEXT NOT NULL CHECK (LENGTH(siren) = 9 AND siren GLOB '[0-9]*'),
            motdepasse TEXT NOT NULL
            )""")

# Table Clients
cur.execute("""CREATE TABLE IF NOT EXISTS Clients (
            id INTEGER PRIMARY KEY AUTOINCREMENT UNIQUE,
            entreprise_id INTEGER,
            nom TEXT NOT NULL,
            prenom TEXT NOT NULL, 
            telephone TEXT NOT NULL CHECK (LENGTH(telephone) = 10 AND telephone GLOB '[0-9]*'),
            num_rue TEXT NOT NULL CHECK (num_rue GLOB '[0-9]* *[a-zA-Z]*'),
            code_postale TEXT NOT NULL CHECK (LENGTH(code_postale) = 5 AND code_postale GLOB '[0-9]*'),
            ville TEXT NOT NULL,
            statut BOOLEAN NOT NULL DEFAULT TRUE,
            FOREIGN KEY (entreprise_id) REFERENCES Entreprises(id)
            )""")

# Table rendezvous
cur.execute("""CREATE TABLE IF NOT EXISTS Rendezvous (
            id INTEGER PRIMARY KEY AUTOINCREMENT UNIQUE,
            client_id INTEGER, 
            entreprise_id INTEGER,
            date DATE NOT NULL, 
            heure TIME NOT NULL,
            etat TEXT NOT NULL CHECK (etat IN ('Confirmé', 'Passé', 'Annulé')),
            num_rue TEXT NOT NULL CHECK (num_rue GLOB '[0-9]* *[a-zA-Z]*'),
            code_postale TEXT NOT NULL CHECK (LENGTH(code_postale) = 5 AND code_postale GLOB '[0-9]*'),
            ville TEXT NOT NULL,
            marque TEXT NOT NULL,
            modele TEXT NOT NULL,
            nbre_siege INT NOT NULL,
            forfait TEXT NOT NULL CHECK (forfait IN ('Forfait Complet', 'Forfait Intérieur', 'Forfait Extérieur')),
            montant INT NOT NULL,
            remarque TEXT NOT NULL,
            FOREIGN KEY (client_id) REFERENCES Clients(id),
            FOREIGN KEY (entreprise_id) REFERENCES Entreprises(id)
            )""")

# Table Photos (pour la suite du projet si j'ai du temps)
cur.execute("""CREATE TABLE IF NOT EXISTS Photos (
            id INTEGER PRIMARY KEY AUTOINCREMENT UNIQUE,
            rendezvous_id INTEGER,
            chemin TEXT, 
            date_ajout DATETIME, 
            FOREIGN KEY (rendezvous_id) REFERENCES RENDEZVOUS(id)
            )""")

# Table Factures
cur.execute("""CREATE TABLE IF NOT EXISTS Factures (
            id INTEGER PRIMARY KEY AUTOINCREMENT UNIQUE,
            rendezvous_id INTEGER,
            entreprise_id INTEGER,
            client_id INTEGER,
            FOREIGN KEY (rendezvous_id) REFERENCES RENDEZVOUS(id),
            FOREIGN KEY (entreprise_id) REFERENCES ENTREPRISES(id),
            FOREIGN KEY (client_id) REFERENCES CLIENTS(id)
            )""")

# Table Transactions
cur.execute("""CREATE TABLE IF NOT EXISTS Transactions (
            id INTEGER PRIMARY KEY AUTOINCREMENT UNIQUE,
            entreprise_id INTEGER,
            type TEXT NOT NULL CHECK (type IN ('+', '-')),
            montant FLOAT NOT NULL,
            date DATETIME NOT NULL,
            description TEXT NOT NULL,
            id_facture INTERGER,
            FOREIGN KEY (entreprise_id) REFERENCES ENTREPRISES(id),
            FOREIGN KEY (id_facture) REFERENCES FACTURES(id)
            )""")

# Table Marque
cur.execute("""CREATE TABLE IF NOT EXISTS Marque (
            ID_Marque INTEGER PRIMARY KEY AUTOINCREMENT UNIQUE,
            Marques TEXT NOT NULL
            )""")

# Table Modele
cur.execute("""CREATE TABLE IF NOT EXISTS Modele (
            ID_Modele INTEGER PRIMARY KEY AUTOINCREMENT UNIQUE,
            Modeles TEXT NOT NULL,
            ID_Marque INTEGER NOT NULL,
            Longueur REAL NOT NULL,
            Largeur REAL NOT NULL,
            Hauteur REAL NOT NULL,
            FOREIGN KEY(ID_Marque) REFERENCES MARQUE(ID_Marque)
            )""")

